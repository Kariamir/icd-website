def esc(t: str) -> str:
    return t.replace('\\', '\\\\').replace("'", "\\'")


def md_bold(t: str) -> str:
    """The article's **bold** markers are kept as-is; the renderer shows plain text."""
    return t.replace('**', '')


def build_blocks() -> str:
    out = []
    for item in BODY:
        if item[0] == 'p':
            out.append(f"      p('{esc(md_bold(item[1]))}'),")
        elif item[0] == 'h':
            out.append(f"      {{ type: 'h2', text: '{esc(item[1])}' }},")
        elif item[0] == 'fig':
            out.append(f"      fig('{item[1]}', '{esc(item[2])}'),")
        elif item[0] == 'list':
            items = ', '.join(f"'{esc(md_bold(x))}'" for x in item[1])
            out.append(f"      {{ type: 'checklist', items: [{items}] }},")
    return '\n'.join(out)


def word_count() -> int:
    words = 0
    for item in BODY:
        if item[0] in ('p', 'h'):
            words += len(md_bold(item[1]).split())
        elif item[0] == 'fig':
            words += len(item[2].split())
        elif item[0] == 'list':
            words += sum(len(md_bold(x).split()) for x in item[1])
    return words


